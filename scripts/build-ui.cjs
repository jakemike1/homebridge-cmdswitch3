"use strict";
const { readFileSync, writeFileSync } = require("node:fs");
const source = readFileSync("config.js", "utf8");
const generated = `// Generated by scripts/build-ui.cjs; validation is shared with the runtime.\n(() => {\nconst module = { exports: {} };\n${source}\nwindow.CmdSwitchConfig = module.exports;\n})();\n`;
const path = "homebridge-ui/public/validation.js";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== generated)
    throw new Error("Run npm run build:ui to refresh browser validation");
} else writeFileSync(path, generated);
